export function pickSites(shift, day = Math.floor(Date.now()/86400000)) {
  const rows=SHIFTS[shift];
  if(!rows) throw Error('Unknown QA shift: '+shift);
  return Array.from({length:3},(_,i)=>{
    const index=((day*3+i)%rows.length+rows.length)%rows.length;
    const [expectedSector,url,country]=rows[index];
    return {kind:expectedSector,expectedSector,url,country};
  });
}
export function validateMatrix(catalogKeys) {
  const all=Object.values(SHIFTS).flat();
  const keys=all.map(e=>e[0]);
  const duplicates=keys.filter((k,i)=>keys.indexOf(k)!==i);
  const missing=catalogKeys.filter(k=>!keys.includes(k));
  const extra=keys.filter(k=>!catalogKeys.includes(k));
  if(all.length!==57||duplicates.length||missing.length||extra.length||
     Object.values(SHIFTS).some(s=>s.length!==19))throw Error('Sector matrix differs from RankFix catalog: '+JSON.stringify({duplicates,missing,extra}));
  for(const [sector,url] of all){
    const u=new URL(url);
    if(u.protocol!=='https:'||!u.hostname||u.username||u.password||u.search||u.hash)throw Error('Unsafe fixture '+sector);
  }
  return true;
}
